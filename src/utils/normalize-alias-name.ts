// Таблица — только в нижнем регистре: приведение к нижнему регистру
// выполняется ДО подстановки гомоглифов, иначе "Т" (заглавная, была бы в
// таблице отдельно) и "т" (строчная) после нормализации расходились бы —
// асимметрия регистр/гомоглиф, пойманная тестом на реальных данных (см. отчёт).
const HOMOGLYPHS: Record<string, string> = {
    'а': 'a',
    'в': 'b',
    'е': 'e',
    'к': 'k',
    'м': 'm',
    'н': 'h',
    'о': 'o',
    'р': 'p',
    'с': 'c',
    'т': 't',
    'х': 'x',
    'у': 'y',
}

const HOMOGLYPH_RE = new RegExp(`[${Object.keys(HOMOGLYPHS).join('')}]`, 'g')

// Единый ключ для поиска/сравнения псевдонимов товара. Убирает различия,
// незаметные кассиру/ОФД при наборе, но значимые для точного сравнения строк:
// регистр, лишние и неразрывные пробелы, кириллица/латиница-двойники.
export const normalizeAliasName = (text: string): string =>
    text
        .toLowerCase()
        .replace(HOMOGLYPH_RE, (ch) => HOMOGLYPHS[ch])
        .replace(/[\s\xa0]+/g, ' ')
        .trim()
